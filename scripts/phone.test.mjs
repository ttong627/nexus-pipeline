//  휴대폰 정규화 회귀 — src/utils/phone.js (2026-08-13 · Phase 0)
//
//  ★이게 틀리면 기사가 자기 배송을 못 본다.
//    Firebase Phone Auth 는 `token.phone_number` 를 **항상 E.164**(`+8210…`)로 준다.
//    우리가 저장한 번호와 문자 그대로 비교해서 통과시키므로, 표기가 흔들리면
//    **에러도 없이** 그 기사만 조용히 막힌다 — 현장에서 배송이 선다.
// ══════════════════════════════════════════════════════════════════
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { toE164Mobile, samePhone, formatPhoneKo } from '../src/utils/phone.js';

const E = '+821012345678';

// ── ① 실제로 들어오는 표기들 ──────────────────────────────────────
test('★같은 번호의 여러 표기가 하나로 모인다', () => {
  for (const v of [
    '010-1234-5678', '01012345678', '010 1234 5678', '010.1234.5678',
    '(010) 1234-5678', ' 010-1234-5678 ', '+82 10-1234-5678', '+821012345678',
    '82 10 1234 5678', '008210-1234-5678',
  ]) {
    assert.equal(toE164Mobile(v), E, `표기 "${v}" 가 다른 값으로 갔다`);
  }
});

test('011·016·017·018·019 대역도 받는다 — 아직 쓰는 기사가 있다', () => {
  assert.equal(toE164Mobile('011-234-5678'), '+82112345678');
  assert.equal(toE164Mobile('016-1234-5678'), '+821612345678');
  assert.equal(toE164Mobile('019-123-4567'), '+82191234567');
});

// ── ② 지어내지 않는다 ────────────────────────────────────────────
test('★판단할 수 없으면 빈 문자열 — 억지로 +82 를 붙이지 않는다', () => {
  // 억지로 붙이면 **다른 사람 번호**가 된다.
  for (const v of ['', null, undefined, '   ', '이름없음', '전화없음', '-', '0']) {
    assert.equal(toE164Mobile(v), '', `"${v}" 를 번호로 만들어냈다`);
  }
});

test('★휴대폰이 아닌 번호는 거른다 — 유선·대표번호로 인증할 수 없다', () => {
  for (const v of ['02-123-4567', '031-123-4567', '1588-1234', '0505-123-4567', '070-1234-5678']) {
    assert.equal(toE164Mobile(v), '', `"${v}" 를 휴대폰으로 받았다`);
  }
});

test('자릿수가 어긋나면 거른다', () => {
  assert.equal(toE164Mobile('010-123-456'), '');       // 짧음
  assert.equal(toE164Mobile('010-1234-56789'), '');    // 김
  assert.equal(toE164Mobile('0101234567'), '+82101234567');  // 10자리는 정상(구 번호)
});

// ── ③ 비교 ───────────────────────────────────────────────────────
test('★표기가 달라도 같은 사람이면 같다고 본다', () => {
  assert.equal(samePhone('010-1234-5678', '+821012345678'), true);
  assert.equal(samePhone('01012345678', '82 10 1234 5678'), true);
});

test('★모르면 통과시키지 않는다 — 한쪽이라도 판단 불가면 false', () => {
  assert.equal(samePhone('', '+821012345678'), false);
  assert.equal(samePhone('없음', '+821012345678'), false);
  assert.equal(samePhone('02-123-4567', '02-123-4567'), false, '유선끼리도 통과하면 안 된다');
});

test('다른 번호는 다르다', () => {
  assert.equal(samePhone('010-1234-5678', '010-1234-5679'), false);
});

// ── ④ 표시 ───────────────────────────────────────────────────────
test('표시용은 익숙한 형태로', () => {
  assert.equal(formatPhoneKo('+821012345678'), '010-1234-5678');
  assert.equal(formatPhoneKo('01012345678'), '010-1234-5678');
  assert.equal(formatPhoneKo('+82101234567'), '010-123-4567');
});

test('★판단 불가면 원문을 지우지 않는다 — 담당자가 무엇이 잘못됐는지 봐야 한다', () => {
  assert.equal(formatPhoneKo('연락처확인필요'), '연락처확인필요');
  assert.equal(formatPhoneKo('02-123-4567'), '02-123-4567');
  assert.equal(formatPhoneKo(''), '');
});

// ── ⑤ Phone Auth 토큰과의 정합 ───────────────────────────────────
test('★Firebase Phone Auth 가 주는 형식(E.164)을 그대로 통과시킨다', () => {
  // 토큰 값을 다시 정규화해도 값이 변하지 않아야 저장값과 비교가 성립한다.
  const fromToken = '+821012345678';
  assert.equal(toE164Mobile(fromToken), fromToken);
  assert.equal(samePhone(fromToken, '010-1234-5678'), true);
});
