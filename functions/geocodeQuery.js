//  지오코딩 질의문 만들기 — **어느 지자체의 주소인지를 반드시 붙인다**
//  회귀: scripts/geocode-query.test.mjs
//
//  ★왜 필요했나 (2026-08-12 실측 사고)
//    정제가 주소를 확정 못 하면(`standardRoadAddress` 없음) 예전 코드는 원문에서 뽑은
//    **도로명 조각**(`매화로 53`)을 그대로 지오코딩에 보냈다. 조각에는 시도·시군구가 없으니
//    **전국에서 아무 데나 맞는다.** 실측 오염 5건(시흥 2026-07 명단):
//
//      매화로 53, 301호 (매화동, 화영주택)        → 성남 분당 야탑동 좌표  (31 km)
//      봉우재로 36 / 37, (정왕동, 번길)           → 서울 중랑구 면목동     (35 km)
//      신천로 1-1, 102- 604호 (신천동, 뉴월드아파트) → 다른 시              (64 km)
//      1길 17, 매화마을 202호 (매화동)            → 다른 도                (201 km)
//
//    저장될 때 `좌표상태='좌표확인'` 이 붙어 **화면에서는 정상으로 보인다.** 아무 에러도 안 난다.
//    기사에게 201km 떨어진 곳을 목적지로 주는 상태였다.
//
//  ★고치는 방향은 "결과를 걸러내기"가 아니라 **"질문을 온전하게 하기"** 다.
//    VWorld getCoord 는 좌표만 주고 **매칭된 주소를 안 돌려준다** — 그래서 응답을 사후
//    대조할 수가 없다(A-36 의 `sameAddressAsQuery` 같은 검증이 여기선 불가능).
//    반면 질의에 `경기도 시흥시` 를 붙이면, 그 시에 그 도로가 없을 때 지오코더가
//    **먼 곳을 주는 대신 NOT_FOUND 를 준다** → 좌표 없음 → 담당자 확인(A-12)으로 넘어간다.
//    **없는 좌표를 지어내지 않는다** — A-36("주소를 지어내지 않는다")과 같은 정신이다.
// ══════════════════════════════════════════════════════════════════

/** 앞뒤 공백·중복 공백 정리. */
const tidy = (v) => String(v ?? '').replace(/\s+/g, ' ').trim();

/**
 * 시도 이름들 — **신·구 표기를 모두 담는다**(개편으로 이름이 바뀐 곳이 있다).
 * 강원·전북은 특별자치도로, 제주는 특별자치도로 바뀌었고 옛 표기가 자료에 여전히 섞여 있다.
 */
const SIDO_NAMES = [
  '서울특별시', '부산광역시', '대구광역시', '인천광역시', '광주광역시', '대전광역시', '울산광역시',
  '세종특별자치시', '경기도',
  '강원특별자치도', '강원도',
  '충청북도', '충청남도',
  '전북특별자치도', '전라북도', '전라남도',
  '경상북도', '경상남도',
  '제주특별자치도', '제주도',
];

/**
 * 이미 **온전한 주소**인가 — 시도 이름으로 시작하면 그렇다.
 *
 * ★호출부가 지자체를 모르는 상황에서도 이 판정은 되어야 한다.
 *   (초기 구현은 `sido` 인자에만 의존해서, 지역을 모르면 온전한 주소까지 버렸다.
 *    회귀 테스트가 그걸 잡았다 — 그래서 이 함수가 따로 있다.)
 */
const looksComplete = (road) => SIDO_NAMES.some((s) => road.startsWith(s));

/**
 * 질의문에 이미 지역이 들어 있는가 — 있으면 덧붙이지 않는다.
 *
 * ★`정제주소`는 이미 `경기도 시흥시 …` 형태라 여기에 시군구를 또 붙이면
 *   `경기도 시흥시 경기도 시흥시 …` 가 되어 도리어 매칭이 깨진다.
 */
const hasRegion = (road, sido, sigungu) => {
  const r = tidy(road);
  if (looksComplete(r)) return true;
  const si = tidy(sigungu);
  const sd = tidy(sido);
  if (si && r.includes(si)) return true;
  if (sd && r.startsWith(sd)) return true;
  return false;
};

/**
 * 지오코딩에 보낼 주소 문자열을 만든다.
 *
 * @param {string} road  정제주소(`standardRoadAddress`) 또는 원문에서 뽑은 도로명 조각
 * @param {string} sido  예: `경기도`
 * @param {string} sigungu 예: `시흥시` (일반구가 있으면 `성남시 중원구` 처럼 공백 포함 가능)
 * @returns {string} 질의문. 도로명이 비면 빈 문자열(호출부가 조회를 건너뛴다).
 */
function buildGeocodeQuery(road, sido, sigungu) {
  const r = tidy(road);
  if (!r) return '';
  if (hasRegion(r, sido, sigungu)) return r;
  const region = tidy(`${tidy(sido)} ${tidy(sigungu)}`);
  // ★지역을 모르면 조각 그대로 보내지 않는다 — 그게 전국 오매칭의 원인이었다.
  //   지역 없이도 온전한 주소(시도로 시작)면 위 hasRegion 에서 이미 통과한다.
  if (!region) return '';
  return `${region} ${r}`;
}

module.exports = { buildGeocodeQuery };
